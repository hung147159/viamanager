        // =========================================================================
        // TEST 1: Cookie snapshot verbatim preservation (Zero Mutation Invariant)
        // =========================================================================
        [Fact]
        public void CookieSerializer_PreservesCookiesVerbatim_ZeroMutation()
        {
            // Arrange: Simulate cookies returned from browser context
            var rawCookies = new List<BrowserContextCookiesResult>
            {
                new() { Name = "c_user", Value = "1000888999111" },
                new() { Name = "xs", Value = "32:actual_fb_session_token_xyz" },
                new() { Name = "fr", Value = "0ABCxyz.test.token" },
                new() { Name = "datr", Value = "randomDatrValue_123" }
            };

            // Act: Serialize verbatim
            string serialized = CookieSerializer.SerializeVerbatim(rawCookies);

            // Assert: ZERO MUTATION!
            // 1. Must NOT inject synthetic "i_user"
            Assert.DoesNotContain("i_user=", serialized);

            // 2. Must NOT override "c_user" with any page id
            Assert.Contains("c_user=1000888999111", serialized);
            Assert.Contains("xs=32:actual_fb_session_token_xyz", serialized);
            Assert.Contains("fr=0ABCxyz.test.token", serialized);
            Assert.Contains("datr=randomDatrValue_123", serialized);

            // 3. FormatPageCookie in CookieHelper must also preserve verbatim
            string helperResult = CookieHelper.FormatPageCookie(rawCookies, "99999999999", "1000888999111");
            Assert.DoesNotContain("i_user=99999999999", helperResult);
            Assert.Contains("c_user=1000888999111", helperResult);
            Assert.Equal(serialized, helperResult);
        }

