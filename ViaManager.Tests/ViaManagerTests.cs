            Assert.Contains(sharedPageId, assignedOther);
        }

        // =========================================================================
        // TEST 7: Concurrent browser profile lock (keyed SemaphoreSlim per UID)
        // =========================================================================
        [Fact]
        public async Task BrowserProfileService_EnforcesKeyedLockPerUid()
        {
            // Arrange
            string testUid = "1000999888";
            var profileLocks = new ConcurrentDictionary<string, SemaphoreSlim>(StringComparer.OrdinalIgnoreCase);

            var sem1 = profileLocks.GetOrAdd(testUid, _ => new SemaphoreSlim(1, 1));

            // Acquire lock in Task 1
            await sem1.WaitAsync();

            bool task2AcquiredLockBeforeRelease = false;
            var task2Started = new TaskCompletionSource<bool>();

            // Task 2 tries to acquire the same UID lock
            var task2 = Task.Run(async () =>
            {
                var sem2 = profileLocks.GetOrAdd(testUid, _ => new SemaphoreSlim(1, 1));
                task2Started.SetResult(true);

                // Wait with a small timeout: should fail to enter because Task 1 holds it
                bool entered = await sem2.WaitAsync(100);
                if (entered)
                {
                    task2AcquiredLockBeforeRelease = true;
                    sem2.Release();
                }
            });

            await task2Started.Task;
            await task2;

            // Assert: Task 2 could NOT acquire the lock while Task 1 held it
            Assert.False(task2AcquiredLockBeforeRelease);

            // Release Task 1
            sem1.Release();

            // Now another task can acquire cleanly
            bool canAcquireAfterRelease = await sem1.WaitAsync(100);
            Assert.True(canAcquireAfterRelease);
            sem1.Release();
        }

        // =========================================================================
        // TEST 8: DPAPI Encryption & Decryption Roundtrip
        // =========================================================================
        [Fact]
        public void SecureDataProtector_EncryptsAndDecryptsCorrectly()
        {
            // Arrange
            string plainSecret = "SuperSecretPassword123!@#";
            string plain2Fa = "JBSWY3DPEHPK3PXP";

            // Act: Protect
            string encryptedPassword = SecureDataProtector.Protect(plainSecret);
            string encrypted2Fa = SecureDataProtector.Protect(plain2Fa);

            // Assert: Encrypted ciphertext is prefixed and not plaintext
            Assert.StartsWith("ENC:", encryptedPassword);
            Assert.NotEqual(plainSecret, encryptedPassword);

            // Act: Unprotect
            string decryptedPassword = SecureDataProtector.Unprotect(encryptedPassword);
            string decrypted2Fa = SecureDataProtector.Unprotect(encrypted2Fa);

            // Assert: Exact fidelity
            Assert.Equal(plainSecret, decryptedPassword);
            Assert.Equal(plain2Fa, decrypted2Fa);

            // Masking test
            string masked = SecureDataProtector.MaskSecret(plainSecret, 2, 2);
            Assert.StartsWith("Su", masked);
            Assert.EndsWith("#", masked);
            Assert.Contains("***", masked);
        }
