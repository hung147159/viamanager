        // =========================================================================
        // TEST 5: Database atomic transaction rollback on failure
        // =========================================================================
        [Fact]
        public void Database_AtomicTransaction_RollsBackOnFailure()
        {
            // Arrange
            var accountRepo = new ViaManager.Data.AccountRepository(_testConnectionString);
            var pageRepo = new PageRepository(_testConnectionString);
            string bm = "Bmv1";
            string viaUid = "100012345";

            // Insert parent VIA account to satisfy Foreign Key constraints
            accountRepo.BatchUpsert(new[]
            {
                new ViaAccount { Uid = viaUid, Status = "live", BusinessManager = bm }
            });

            // Create a valid page
            var validPage = new ManagedPage
            {
                PageId = "61550001111111",
                Name = "Page 1",
                RawCookieSnapshot = "c_user=100012345; datr=abc;"
            };

            // Verify clean state
            Assert.Empty(pageRepo.GetAllAssignedPageIds());

            // Act: Insert valid page successfully
            pageRepo.AssignPagesAtomic(bm, viaUid, new[] { validPage });
            Assert.Single(pageRepo.GetAllAssignedPageIds());

            // Try to insert a batch that fails in transaction
            // We simulate a transaction failure using a custom connection with a locking condition or invalid SQL trigger
            using (var conn = new SqliteConnection(_testConnectionString))
            {
                conn.Open();
                using var cmd = conn.CreateCommand();
                cmd.CommandText = @"
                    CREATE TRIGGER FailTrigger_AssignedPages
                    BEFORE INSERT ON AssignedPages
                    WHEN NEW.Page_ID = 'TRIGGER_FAIL'
                    BEGIN
                        SELECT RAISE(ABORT, 'Simulated database transaction abort.');
                    END;
                ";
                cmd.ExecuteNonQuery();
            }

            var batchWithFailure = new[]
            {
                new ManagedPage { PageId = "61550002222222", Name = "Page 2", RawCookieSnapshot = "cookie" },
                new ManagedPage { PageId = "TRIGGER_FAIL", Name = "Page Fail", RawCookieSnapshot = "cookie" }
            };

            // Assert that transaction throws and rolls back Page 2
            Assert.Throws<SqliteException>(() =>
            {
                pageRepo.AssignPagesAtomic(bm, viaUid, batchWithFailure);
            });

            // Page 2 must NOT exist in database because transaction rolled back!
            var currentPages = pageRepo.GetAllAssignedPageIds();
            Assert.Single(currentPages); // Only original validPage remains
            Assert.DoesNotContain("61550002222222", currentPages);
        }

